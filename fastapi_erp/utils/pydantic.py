# /utils/pydantic.py

from __future__ import annotations

from typing import Any

from pydantic import ConfigDict, create_model
from sqlalchemy import inspect

def to_camel(value: str) -> str:
    parts = value.split("_")

    return parts[0] + "".join(
        part.capitalize()
        for part in parts[1:]
    )

def to_pydantic(
    model: type,
    *,
    name: str | None = None,
    include: set[str] | None = None,
    exclude: set[str] | None = None,
    optional: set[str] | None = None,
    required: set[str] | None = None,
    all_optional: bool = False,
    exclude_autogenerated: bool = False,
):
    """
    Genera dinámicamente un modelo Pydantic a partir de un modelo SQLAlchemy.

    Reglas:
        - nullable=True       -> T | None = None
        - default=<valor>     -> T = <valor>
        - nullable=False      -> T obligatorio
        - optional={...}      -> fuerza T | None = None
        - required={...}      -> fuerza T obligatorio
        - all_optional=True   -> todos T | None = None
    """

    mapper = inspect(model)

    include = set(include) if include is not None else None
    exclude = set(exclude or ())
    optional = set(optional or ())
    required = set(required or ())

    conflict = optional & required

    if conflict:
        raise ValueError(
            f"Fields cannot be both optional and required: {conflict}"
        )

    fields: dict[str, tuple[Any, Any]] = {}

    for column in mapper.columns:
        field_name = column.key

        # ---------------------------------------------------------
        # Include / exclude
        # ---------------------------------------------------------

        if include is not None and field_name not in include:
            continue

        if field_name in exclude:
            continue

        # ---------------------------------------------------------
        # Columnas autogeneradas
        # ---------------------------------------------------------

        if exclude_autogenerated:
            autogenerated = (
                (column.primary_key and column.autoincrement is not False)
                or column.default is not None
                or column.server_default is not None
            )

            if autogenerated:
                continue

        # ---------------------------------------------------------
        # Tipo Python
        # ---------------------------------------------------------

        try:
            python_type = column.type.python_type
        except (AttributeError, NotImplementedError):
            python_type = Any

        # ---------------------------------------------------------
        # Required explícito tiene máxima prioridad
        # ---------------------------------------------------------

        if field_name in required:
            fields[field_name] = (
                python_type,
                ...,
            )
            continue

        # ---------------------------------------------------------
        # Optional explícito / all_optional
        # ---------------------------------------------------------

        if all_optional or field_name in optional:
            fields[field_name] = (
                python_type | None,
                None,
            )
            continue

        # ---------------------------------------------------------
        # Default definido en SQLAlchemy
        #
        # Ejemplo:
        # Column(Boolean, nullable=False, default=False)
        #
        # ->
        #
        # active: bool = False
        # ---------------------------------------------------------

        if column.default is not None:
            default = column.default

            # Solo copiamos defaults escalares.
            #
            # default=False
            # default=0
            # default="..."
            #
            # Los callable/default SQL expressions no deben
            # ejecutarse al generar el modelo Pydantic.
            if default.is_scalar:
                fields[field_name] = (
                    python_type,
                    default.arg,
                )
                continue

        # ---------------------------------------------------------
        # Nullable
        # ---------------------------------------------------------

        if column.nullable:
            fields[field_name] = (
                python_type | None,
                None,
            )
            continue

        # ---------------------------------------------------------
        # Obligatorio
        # ---------------------------------------------------------

        fields[field_name] = (
            python_type,
            ...,
        )

    model_name = name or f"{model.__name__}Schema"

    return create_model(
        model_name,
        __config__=ConfigDict(
        from_attributes=True,
        extra="ignore",
        alias_generator=to_camel,
        populate_by_name=True,
    ),
        **fields,
    )